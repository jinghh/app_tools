package com.jhh.myapptools.ui.theme

import androidx.compose.material3.Typography
import androidx.compose.ui.text.TextStyle
import androidx.compose.ui.text.font.FontFamily
import androidx.compose.ui.text.font.FontWeight
import androidx.compose.ui.unit.sp

/**
 * 排版层次。
 *
 * 之前完全用 Material3 默认 Typography：标题和正文的**字重几乎一样**，
 * 页面里"哪里是标题、哪里是说明"只能靠字号差 2sp 来区分，观感松散。
 *
 * 这里的主要调整：
 * - 大标题加重（SemiBold）+ **负字距**（大字号收紧更现代，中文同理）；
 * - 卡片标题（titleMedium）用 SemiBold，和正文拉开层次；
 * - 辅助文字（bodySmall）用更小的行高，减少长文案的压迫感；
 * - 标签/按钮（labelLarge）用 Medium，避免按钮文字看起来"太粗"。
 */
val AppTypography = Typography(
    headlineSmall = TextStyle(
        fontFamily = FontFamily.Default,
        fontWeight = FontWeight.SemiBold,
        fontSize = 24.sp,
        lineHeight = 30.sp,
        letterSpacing = (-0.3).sp,
    ),
    titleLarge = TextStyle(
        fontFamily = FontFamily.Default,
        fontWeight = FontWeight.SemiBold,
        fontSize = 20.sp,
        lineHeight = 26.sp,
        letterSpacing = (-0.2).sp,
